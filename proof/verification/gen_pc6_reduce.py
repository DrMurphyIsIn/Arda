"""PairCollapse6 REDUCTION-lemma generator (A3(2) bridge, stage 2(ii) batch).

Emits `proof/formalization/R3Cert/R47PC6Reduce.lean`: for every cell of the frozen selection
table and each clause (W1, W2' at weight 1/6, ROOT), the count-form statistic inequality

    <pair statistic>  <=  <target statistic>

proved by the VALIDATED atom-factored template (findings Addendum 5):
    L1  hXY : X <= Y        -- emitted key identity  Y - X = (m*POLY)/(mden*DEN), then the
                               R47PC6Cells polynomial certificate via div_nonneg;
    L2  hL  : pair = A * X,  hR : target = A * Y  -- closed-form rewrites + field_simp; ring;
    L3  calc compose with mul_le_mul_of_nonneg_left.

A = V5^a5 * V4^a4 * V5^b5 * V4^b4 (the positive power block); X, Y are atom-free rational
functions of the four count casts, computed with sympy `cancel` in the opaque-atom model; the
key-identity numerator is verified = m * cellpoly at emission (a mismatch refuses to emit).
Negative candidate components (x or y < 0) use Nat subtraction in the target counts with
`push_cast [Nat.cast_sub ...]` + `pow_sub₀` exponent splits.

Usage:  python3 proof/verification/gen_pc6_reduce.py [--check]
conjecture1_proved = False.
"""
