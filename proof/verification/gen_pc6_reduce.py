    for cA in range(0, 6):
        for cb in range(0, 6):
            main.append(f"    | exact pc6a_{cA}_{cb} armsA armsB hbA hbB hA5 hB5")
    out.append("\n".join(main) + "\n")
    out.append("end PC6\nend Step3\nend R3Cert\n")
