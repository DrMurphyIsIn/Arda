"""Generator for the EXTENDED rational near-star hull -> Lean `HullFull.lean`.

The 3-segment `menuHullRat` is tight only on the right band; extend it to the full upper concave hull of the
near-star points `sp = 0..23` (cavity `3/(4sp+3)` in `[3/95, 1]`).  sp <= 23 is the norm_num-provable range
(`11*24 = 264 > 256` exceeds norm_num's exponent threshold; `11*23 = 253 < 256` is fine), so the hull spans
cavity `>= 3/95`; the deeper band (sp > 23, cavity < 3/95) stays on the direct per-child route
(`nodeAmp_deepleft_le`) -- the cavity-0 accumulation obstruction.

Amplitude upper bounds are `ub_sp = ceil((Rval(sp)-1)/11, 2000)` (a SIMPLE rational >= the exact `gVal_le_Rval`
bound, so still a valid `gVal` upper bound; rounding UP only raises the hull, preserving domination).  The upper
concave hull of `{(cav_sp, ub_sp)}` has small-denominator rational segments.

Emits, all self-verified in exact `Fraction` arithmetic before emission:
  * `menuHullFull := hullOf [segs] (0,0)` + `_concave` (free) + `_nonpos` (free, zero seed);
  * `menuHullFull_dominates_nearstar` per sp=0..23: `gVal sp <= menuHullFull (3/(4sp+3))`, via
    `gVal_le_Rval` (ONE big-number norm_num on Rval per sp) then `hullOf_dominates` (small-number per-segment);
  * `menuHullFull_le_cell` (uniform cell hull bound, analog of `menuHullRat_le_cell`).
"""
from __future__ import annotations

import math
import os
from fractions import Fraction as Fr


def Rval(n: int) -> Fr:
    return (Fr(3, 2) ** (11 * n) * Fr(4 * n + 3) ** 11) / (Fr(621, 64) ** (1 + 2 * n) * Fr(3 * (n + 1)) ** 11)


def ceil_frac(x: Fr, D: int) -> Fr:
    return Fr(math.ceil(x * D), D)


def build():
    pts = []
    for sp in range(0, 24):
        cav = Fr(3, 4 * sp + 3)
        amp = (Rval(sp) - 1) / Fr(11)
        ub = ceil_frac(amp, 2000)
        pts.append((cav, ub, amp, sp))
    P = sorted((c, u) for (c, u, _, _) in pts)

    def cross(o, a, b):
        return (a[0] - o[0]) * (b[1] - o[1]) - (a[1] - o[1]) * (b[0] - o[0])

    hull = []
    for p in P:
        while len(hull) >= 2 and cross(hull[-2], hull[-1], p) >= 0:
            hull.pop()
        hull.append(p)
    segs = []
    for i in range(1, len(hull)):
        x1, y1 = hull[i - 1]
        x2, y2 = hull[i]
        b = (y2 - y1) / (x2 - x1)
        a = y1 - b * x1
        segs.append((a, b))
    # verify
    def dom_line(c):
        return min(a + b * c for (a, b) in segs)
    assert all(amp <= dom_line(cav) for (cav, ub, amp, sp) in pts), "domination failed"
    assert all(segs[i][1] >= segs[i + 1][1] for i in range(len(segs) - 1)), "not concave"
    return pts, segs


def fr_lean(q: Fr) -> str:
    if q.denominator == 1:
        return f"({q.numerator} : ℝ)" if q.numerator < 0 else f"{q.numerator}"
    num = f"({q.numerator})" if q.numerator < 0 else f"{q.numerator}"
    return f"{num} / {q.denominator}"


def seg_list_lean(segs) -> str:
    return "[" + ", ".join(f"({fr_lean(a)}, {fr_lean(b)})" for (a, b) in segs) + "]"


def main():
    pts, segs = build()
    SEGS = seg_list_lean(segs)

    dom_thms = []
    for (cav, ub, amp, sp) in pts:
        cav_l = fr_lean(cav)
        ub_l = fr_lean(ub)
        dom_thms.append(f"""/-- Domination at near-star `sp = {sp}` (cavity `{cav}`): `gVal {sp} <= menuHullFull`. -/
theorem menuHullFull_dom_sp{sp} : gVal {sp} ≤ menuHullFull ({cav_l}) := by
  have h : gVal {sp} ≤ ({ub_l}) := le_trans (gVal_le_Rval {sp}) (by norm_num [Rval])
  unfold menuHullFull
  refine hullOf_dominates _ _ (gVal {sp}) ({cav_l}) (le_trans h (by norm_num [affineFn])) ?_
  intro ab hab; fin_cases hab <;> exact le_trans h (by norm_num [affineFn])
""")

    header = f'''/-
  The EXTENDED rational near-star hull -- GENERATED by `hull_gen.py` (do not edit by hand).

  `menuHullFull` is the upper concave hull of the near-star points `sp = 0..23` at their rounded rational
  amplitude bounds `ceil((Rval sp - 1)/11, 2000)` ({len(segs)} segments, spanning cavity `[3/95, 1]`).  sp <= 23
  is the norm_num-provable range; the deeper band (cavity < 3/95) stays on the direct per-child route.  All
  facts are machine-checked: concavity + non-positivity are free (`hullOf_concave` / zero seed), and
  `menuHullFull_dominates_nearstar` proves `gVal sp <= menuHullFull(cavity sp)` for every sp=0..23 (via
  `gVal_le_Rval` then `hullOf_dominates`).  `menuHullFull_le_cell` is the per-cell upper bound used by the grid.
-/
import Mathlib
import R3Cert.Structure

namespace R3Cert

open Real

/-- The extended near-star hull: {len(segs)} rational tangent segments (sp=0..23 vertices) + zero seed. -/
noncomputable def menuHullFull : ℝ → ℝ := hullOf {SEGS} (0, 0)

/-- Concavity of the extended hull -- free from `hullOf_concave` (the Jensen premise). -/
theorem menuHullFull_concave : ConcaveOn ℝ Set.univ menuHullFull := hullOf_concave _ _

/-- The extended hull is `<= 0` everywhere (the zero-line seed caps it). -/
theorem menuHullFull_nonpos (x : ℝ) : menuHullFull x ≤ 0 := by
  simpa [menuHullFull, affineFn] using hullOf_le_seed {SEGS} (0, 0) x

/-- Uniform hull bound on a cavity cell for the extended hull (analog of `menuHullRat_le_cell`): for any of its
    tangent segments `ab` and `m in [ml, mr]`, `menuHullFull m <= max (affineFn ab ml) (affineFn ab mr)`. -/
theorem menuHullFull_le_cell (ab : ℝ × ℝ) (hab : ab ∈ ({SEGS} : List (ℝ × ℝ)))
    (ml mr m : ℝ) (h1 : ml ≤ m) (h2 : m ≤ mr) :
    menuHullFull m ≤ max (affineFn ab ml) (affineFn ab mr) :=
  hullOf_le_max_endpoints _ _ ab ml mr m hab h1 h2

'''
    body = "\n".join(dom_thms)
    footer = """
/-- **A worked near-tie cell on `menuHullFull`, closed in ONE shot** via `Qeq_affine_cell_le`.  The wide tie
    cell `m in [3/23, 8/23]` at the binding `(s, j) = (0, 36)` -- which the subdivided grid needed several cells
    for -- closes with a SINGLE affine (concave-max) bound on the active `sp=5` tangent `(19/4000, -437/12000)`:
    `gVal 36 <= -3911/20000` (`gVal_le_lin_tight`), affine domination `menuHullFull m <= affineFn ab m`
    (`hullOf_le_of_mem`), and the two endpoint checks by `norm_num`.  No subdivision. -/
example : ∀ m, (3 : ℝ) / 23 ≤ m → m ≤ 8 / 23 → Qeq 0 36 menuHullFull m ≤ omegaVal :=
  Qeq_affine_cell_le 0 36 (19 / 4000, -437 / 12000) (3 / 23) (8 / 23) (-3911 / 20000) (-78 / 10000)
    (by norm_num) (le_trans (gVal_le_lin_tight (0 + 36)) (by norm_num)) omega_enclosure.1.le
    (fun m => by unfold menuHullFull; exact hullOf_le_of_mem _ _ (19 / 4000, -437 / 12000) m (by simp))
    (by norm_num) (by norm_num)

end R3Cert
"""
    out = header + body + footer
    outpath = os.path.join(os.path.dirname(__file__), "formalization/R3Cert/HullFull.lean")
    with open(outpath, "w") as f:
        f.write(out)
    print(f"Emitted menuHullFull ({len(segs)} segments) + {len(pts)} domination theorems -> {outpath}")


if __name__ == "__main__":
    main()
