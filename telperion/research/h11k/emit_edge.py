"""UNTRUSTED emitter (lane H11K): the top edge of the band as H11K_Edge_T<T>.lean, per-piece decides."""
import sys, pickle, os
sys.path.insert(0, '/Users/peterwmurphy/arda-h11k/telperion/examples/zeta_reflection')
import Arb4_emit as A
from fractions import Fraction as Fr
ISL = '/Users/peterwmurphy/arda-h11k/telperion/examples/zeta_reflection/lean'
T = sys.argv[1]; out = sys.argv[2]; which = sys.argv[3] if len(sys.argv) > 3 else 'all'
e = pickle.load(open('edge_%s.pkl' % T, 'rb'))
name = 'E_' + A.edge_tag(e['T'])
m = len(e['pieces'])
js = range(m) if which == 'all' else [int(x) for x in which.split(',')]
L = ['/-  %s.lean -- lane H11K: the kernel certificate of the horizontal argument change at T = %s.' % (out, T),
     '',
     '    (GENERATED by scratchpad h11k/emit_edge.py, UNTRUSTED; every value is re-checked here.)  The edge data',
     '    `Arb4.EdgeD` (%d octant pieces, EM cut N = %d, planned by emit_h1000_offline.plan_edge, unchanged) and' % (m, e['N']),
     '    ONE `decide +kernel` per piece (`H11K.pieceJ`) plus one for the rest (`H11K.edgeRest`), assembled by',
     '    `H11K.edge_sound_of_split` (the whole-edge `Arb4.edgeOK` decide is about 19 GB at this height).',
     '    conjecture1_proved = False.  Finite verification up to a fixed height only.',
     '-/',
     'import H11K_EdgeSplit', '', 'open Arb4 Arb4.Q H11K', '', 'namespace H11K.Edge', '',
     '/-- The edge `[2, -1] + i %s` (%d pieces, N = %d). -/' % (T, m, e['N']),
     A.edge_def(e, name), '',
     'theorem %s_rest : edgeRest %s = true := by decide +kernel' % (name, name), '']
for j in js:
    L.append('theorem %s_p%d : pieceJ %s %d = true := by decide +kernel' % (name, j, name, j))
    L.append('')
if which == 'all':
    L.append('theorem %s_pieces : ∀ j, j < %s.m → pieceJ %s j = true := by' % (name, name, name))
    L.append('  intro j hj')
    L.append('  have hm : %s.m = %d := rfl' % (name, m))
    L.append('  rw [hm] at hj')
    L.append('  interval_cases j')
    for j in range(m):
        L.append('  · exact %s_p%d' % (name, j))
    L.append('')
    L.append('/-- **The horizontal argument change at T = %s, hypothesis-free.** -/' % T)
    L.append('theorem %s_hAH : DiffractionCore.argChangeHoriz riemannZeta %s 2 (-1) ∈' % (name, A.rl(e['T'])))
    L.append('    Set.Icc %s.Lo.val %s.Hi.val := by' % (name, name))
    L.append('  have h := edge_sound_of_split %s %s_rest %s_pieces' % (name, name, name))
    L.append('  have hT : %s.T = %s := by' % (name, A.rl(e['T'])))
    L.append('    show ((%d : ℕ) : ℝ) / 2 ^ (%d : ℕ) = %s' % (e['tn'], e['tq'], A.rl(e['T'])))
    L.append('    norm_num')
    L.append('  rw [hT] at h')
    L.append('  exact h')
    L.append('')
L.append('end H11K.Edge')
L.append('')
dest = ISL if which == 'all' else '.'
open(os.path.join(dest, out + '.lean'), 'w').write('\n'.join(L))
print('wrote', out, 'Lo', e['Lv'], 'Hi', e['Hv'])
