"""Memory-bounded S9 certificate modules (CI OOM fix, 2026-10-12).

The kernel keeps its reduction caches per declaration, so peak RSS is governed by the work done in
ONE `decide +kernel` theorem.  The original ArchS9_CertGram1 checked 225 Gram entries in one
declaration (21 GB peak).  This script emits one small `decide +kernel` theorem per chunk of at most
CH Gram entries (~0.8 GB above the 5.7 GB Mathlib+data baseline), one per E row, one per window, and
re-derives the ORIGINAL statements (gram_rows_1..4, e_rows_1/2, windows_ok) from them by list
lemmas only, so every downstream statement and name is unchanged.  The data (ArchS9_Data) is not
touched.  Usage: python gen_s9_split.py LEANDIR.   conjecture1_proved = False."""
import sys, os
D = sys.argv[1]
J, CH = 40, 10
HDR = """/-
  {name} -- {what}
  (archimedean stage S9, memory-bounded split of 2026-10-12; GENERATED by
  telperion/research/arch_rung/s9/gen_s9_split.py).  Each `decide +kernel` theorem is a separate
  declaration so the kernel's reduction caches are released between them (peak RSS per module stays
  near the Mathlib baseline).  conjecture1_proved = False.  No `sorry`.
-/
"""
def w(name, body):
    open(os.path.join(D, name + ".lean"), "w").write(body)

w("ArchS9_GramChunk", HDR.format(name="ArchS9_GramChunk", what="chunked Gram checker and list-chaining lemmas") + """import ArchS9_Data

namespace ArchS9.Data

/-- The Gram predicate of `gramRowOK n`, for one column `m`. -/
def gramPred (n m : ℕ) : Bool :=
  decide (|(gz n m : ℚ) - (if n = m then DDL else 0)| ≤ gamQ * DDL)

/-- Columns `a .. a+b-1` of Gram row `n`. -/
def gramChunkOK (n a b : ℕ) : Bool := (List.range' a b).all (gramPred n)

theorem all_of_chunks {f : ℕ → Bool} {a b c : ℕ} (h1 : (List.range' a b).all f = true)
    (h2 : (List.range' (a + b) c).all f = true) : (List.range' a (b + c)).all f = true := by
  rw [List.all_eq_true] at h1 h2 ⊢
  intro x hx
  rw [List.mem_range'_1] at hx
  by_cases h : x < a + b
  · exact h1 x (List.mem_range'_1.mpr ⟨hx.1, h⟩)
  · exact h2 x (List.mem_range'_1.mpr ⟨by omega, by omega⟩)

theorem all_one {f : ℕ → Bool} {n : ℕ} (h : f n = true) : (List.range' n 1).all f = true := by
  rw [List.all_eq_true]
  intro x hx
  rw [List.mem_range'_1] at hx
  obtain rfl : x = n := by omega
  exact h

end ArchS9.Data
""")

def chain(facts):
    """facts: list of terms each proving (range' s_i b_i).all f; consecutive. Left fold."""
    t = facts[0]
    for f in facts[1:]:
        t = f"(all_of_chunks {t} {f})"
    return t

groups = [(0, 6), (6, 13), (13, 22), (22, 40)]      # rows of CertGram1..4
for gi, (r0, r1) in enumerate(groups, 1):
    rows = list(range(r0, r1))
    half = [rows[: (len(rows) + 1) // 2], rows[(len(rows) + 1) // 2:]]
    for hi, hrows in enumerate(half):
        mod = f"ArchS9_CertGram{gi}{'ab'[hi]}"
        lines = [HDR.format(name=mod, what=f"Gram chunks, rows {hrows[0]}-{hrows[-1]}"), "import ArchS9_GramChunk\n",
                 "namespace ArchS9.Data\n", "set_option maxRecDepth 100000\n"]
        for n in hrows:
            a = n
            while a < J:
                b = min(CH, J - a)
                lines.append(f"theorem gc_{n}_{a} : gramChunkOK {n} {a} {b} = true := by decide +kernel\n")
                a += b
        lines.append("end ArchS9.Data\n")
        w(mod, "\n".join(lines))
    # derived module (old name, old statement)
    lines = [HDR.format(name=f"ArchS9_CertGram{gi}", what=f"Gram rows {r0}-{r1 - 1} (derived from chunk certificates; no decide)"),
             f"import ArchS9_CertGram{gi}a\nimport ArchS9_CertGram{gi}b\n", "namespace ArchS9.Data\n"]
    for n in rows:
        facts, a = [], n
        while a < J:
            b = min(CH, J - a)
            facts.append(f"gc_{n}_{a}")
            a += b
        lines.append(f"theorem gram_row_{n} : gramRowOK {n} = true := {chain(facts)}\n")
    rowfacts = [f"(all_one gram_row_{n})" for n in rows]
    lines.append(f"theorem gram_rows_{gi} : (List.range' {r0} {r1 - r0}).all gramRowOK = true :=\n  {chain(rowfacts)}\n")
    lines.append("end ArchS9.Data\n")
    w(f"ArchS9_CertGram{gi}", "\n".join(lines))

# E rows
lines = [HDR.format(name="ArchS9_CertE", what="row bounds of E = diag(aR) - B^T Theta B, one declaration per row"),
         "import ArchS9_GramChunk\n", "namespace ArchS9.Data\n", "set_option maxRecDepth 100000\n"]
for j in range(J):
    lines.append(f"theorem e_row_{j} : eRowOK {j} = true := by decide +kernel\n")
for k, (a, b) in enumerate([(0, 20), (20, 20)], 1):
    lines.append(f"theorem e_rows_{k} : (List.range' {a} {b}).all eRowOK = true :=\n  {chain([f'(all_one e_row_{j})' for j in range(a, a + b)])}\n")
lines.append("end ArchS9.Data\n")
w("ArchS9_CertE", "\n".join(lines))

# Misc
lines = [HDR.format(name="ArchS9_CertMisc", what="constants, the 13 windows (one declaration each), localization, negative control"),
         "import ArchS9_GramChunk\n", "namespace ArchS9.Data\n", "set_option maxRecDepth 100000\n",
         "theorem lc_ok : lcOK = true := by decide +kernel\n",
         "theorem const_ok : constOK = true := by decide +kernel\n"]
for n in range(13):
    lines.append(f"theorem window_ok_{n} : windowOK {n} = true := by decide +kernel\n")
lines.append(f"theorem windows_ok : (List.range (NCw + 1)).all windowOK = true := by\n"
             f"  rw [List.range_eq_range']\n"
             f"  exact {chain([f'(all_one window_ok_{n})' for n in range(13)])}\n")
lines.append("theorem loc_ok : locOK = true := by decide +kernel\n")
lines.append("""/-- NEGATIVE CONTROL: shrinking the second-round window of n = 0 by a factor 10 breaks the
certificate (the residual bound eps forces |λ - θ 0| up to about 6.7e-43), so `windows_ok` is not
vacuous. -/
theorem window_negative_control :
    roundOK 0 (w1q 0) (R1q 0) (pi1q 0) (w2q 0 / 10) = false := by decide +kernel
""")
lines.append("end ArchS9.Data\n")
w("ArchS9_CertMisc", "\n".join(lines))
print("ok")
