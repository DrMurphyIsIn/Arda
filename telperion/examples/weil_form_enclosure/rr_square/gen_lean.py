def lean_rat(x):
    x = Fr(x)
    return f"({x.numerator} : ℝ)" if x.denominator == 1 else f"(({x.numerator} : ℝ) / {x.denominator})"

def mat(G):
    rows = [", ".join(str(int(Fr(x))) for x in row) for row in G]
    return "!![" + ";\n    ".join(rows) + "]"

def lin(l):  # sum l_j v j
    terms = [f"{lean_rat(c)} * v {j}" for j, c in enumerate(l) if Fr(c) != 0]
    return " + ".join(terms) if terms else "0"

def cert_rhs(ds, ls):
    return " + ".join(f"{lean_rat(d)} * ({lin(l)}) ^ 2" for d, l in zip(ds, ls))

