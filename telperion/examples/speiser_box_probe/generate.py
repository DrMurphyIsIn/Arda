"""Generate the MM_speiser_box_probe island: certify -> emit certificate arithmetic + sidecar.

    python examples/speiser_box_probe/generate.py           # write Cert.lean + .cert.json
    python examples/speiser_box_probe/generate.py --check    # byte-for-byte drift check

SCOPE, stated plainly and meant literally.  The target is:

    `deriv riemannZeta` has no zero in the closed rectangle [1/4, 3/8] x [6, 10].

This is **NOT** the Speiser wall.  Speiser (1935) showed that non-vanishing of `zeta'` on
the WHOLE open left strip `0 < re s < 1/2` is EQUIVALENT to the Riemann Hypothesis.  One
bounded rectangle -- or any finite union of them -- decides nothing about RH, because no
finite union of boxes exhausts a strip.  This island is a pilot for the winding-certificate
face, retargeted from `zeta` to `zeta'`.  Nothing here is a step toward RH.
conjecture1_proved = False.

WHAT IS AND IS NOT PROVED.  The Lean island proves, unconditionally and axiom-clean:
the general Lipschitz-net instrument `nonvanishing_of_grid`, the box geometry (convexity,
the eight-point net), the holomorphy of `deriv riemannZeta` on the box, and the capstone
`speiser_box_probe_of_numeric` MODULO exactly two named numeric obligations.  This
generator emits the certificate ARITHMETIC (the exact rational inequalities that make the
net close) as four further kernel theorems.  The two numeric obligations --
`SecondDerivBoundOnBox` (`|zeta''| <= 3/10` on the box) and `GridModulusLowerBound`
(`|zeta'| >= 1/10` at the eight grid points) -- are NOT proved here or anywhere in this
repository.  The mpmath re-derivation below is EVIDENCE and a REFUSAL INSTRUMENT, not a
proof: trust class `mpmath-numeric`, which is weaker than Arb interval arithmetic.
"""
import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "src"))

from telperion import (  # noqa: E402
    GridModulusNonvanishingEmitter, ValidationReport, certify, emit,
)
from telperion.emit_grid_modulus_nonvanishing import (  # noqa: E402
    grid_modulus_nonvanishing_family,
)
from telperion.family import GridSpec  # noqa: E402
from telperion.lean import LeanProfile  # noqa: E402

_HERE = Path(__file__).resolve().parent
_OUT_LEAN = _HERE / "lean" / "SpeiserBoxProbe" / "Cert.lean"
_OUT_JSON = _HERE / "SpeiserBoxProbe.cert.json"

# The eight grid rows: one column at re = 5/16 (the box mid-line), rows at 6 + (2k+1)/4.
_ROWS = ["25/4", "27/4", "29/4", "31/4", "33/4", "35/4", "37/4", "39/4"]

_SPEC = {
    "re0": "1/4", "re1": "3/8", "im0": "6", "im1": "10",
    "grid_re": "5/16", "grid_im": _ROWS,
    "half_width": "1/16", "half_height": "1/4",
    "delta": "13/50",      # >= sqrt(1/256 + 1/16) = sqrt 17 / 16 = 0.25769...
    "bound_M": "3/10",     # >= sup |zeta''| on the box (observed 0.2823...)
    "bound_L": "1/10",     # <= min |zeta'| on the grid (observed 0.2020...)
    "backend": "riemannZeta", "prec": 30, "sweep_nre": 8, "sweep_nim": 40,
}

_HEADER = """/-
  DO NOT EDIT BY HAND -- generated by examples/speiser_box_probe/generate.py.

  The certificate ARITHMETIC for the MM_speiser_box_probe Face-7 pilot box: the exact
  rational inequalities that make the Lipschitz net exclude a zero of `deriv riemannZeta`
  on [1/4, 3/8] x [6, 10].  Corrupting the certificate (understating `delta`, inflating
  `boundL`, shrinking `boundM`, loosening the grid) makes these `norm_num` goals FAIL.

  NOT the Speiser wall: Speiser (1935) makes non-vanishing of `zeta'` on the WHOLE open
  left strip equivalent to RH, and no finite union of boxes exhausts a strip.  Verifying
  this box decides nothing about RH.  conjecture1_proved = False.
-/
"""


def build() -> tuple[str, list[dict]]:
    fam = grid_modulus_nonvanishing_family(
        "SpeiserBoxCert",
        GridSpec([("case", [0])]),
        lambda pt: "speiser_box_cert",
        spec=lambda pt: _SPEC,
    )
    em = GridModulusNonvanishingEmitter()
    report = emit(
        certify(fam),
        LeanProfile(namespace=("SpeiserBoxCert",)),
        [em],
        ValidationReport(checks=(("grid_modulus_nonvanishing", True),)),
    )
    emitted = next(iter(report.files.values()))
    return _HEADER + emitted, em._cert_sink


def main(*, check: bool = False) -> int:
    lean, sidecars = build()
    sidecar_text = json.dumps(sidecars, indent=2, sort_keys=True) + "\n"
    if check:
        drift = False
        if not _OUT_LEAN.exists() or _OUT_LEAN.read_text(encoding="utf-8") != lean:
            print("DRIFT: lean/SpeiserBoxProbe/Cert.lean does not match regeneration")
            drift = True
        if not _OUT_JSON.exists() or _OUT_JSON.read_text(encoding="utf-8") != sidecar_text:
            print("DRIFT: SpeiserBoxProbe.cert.json does not match regeneration")
            drift = True
        if drift:
            return 1
        print("check: OK (certificate arithmetic + sidecar match regeneration byte-for-byte)")
        return 0
    _OUT_LEAN.parent.mkdir(parents=True, exist_ok=True)
    _OUT_LEAN.write_text(lean, encoding="utf-8")
    _OUT_JSON.write_text(sidecar_text, encoding="utf-8")
    print(f"wrote {_OUT_LEAN} + {_OUT_JSON} ({len(sidecars)} certificate(s))")
    return 0


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="drift check; do not write")
    raise SystemExit(main(check=ap.parse_args().check))
