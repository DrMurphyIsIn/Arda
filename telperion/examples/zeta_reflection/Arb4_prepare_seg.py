"""Arb4_prepare_seg.py -- lane Arb4: prepare ladder segment [H - 1000, H] (H >= 3000) for the compact
pipeline: the band table (emit_band_glue.py on the zeta_zero_localization band plan `AllZeros_h<H>`,
namespace prefixed `Arb4.`) and the lakefile entries (APPENDED): the zzl band plan sources (unchanged)
as `Arb4_ZZLSegment_h<H>`, the band table, the compact certificate libraries, capstone and guard.

usage: Arb4_prepare_seg.py H        (then: Arb4_emit_seg.py --seg H; lake build Arb4_h<H> Arb4_AxiomGuard_h<H>)
conjecture1_proved = False.
"""
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
LEAN = os.path.join(HERE, "lean")
ZZL = os.path.join(HERE, "..", "zeta_zero_localization", "lean")


def main():
    H = int(sys.argv[1])
    assert H % 1000 == 0 and H >= 3000
    raw = os.path.join(LEAN, ".Arb4_bandglue_raw_h%d.lean" % H)
    subprocess.check_call([sys.executable, os.path.join(HERE, "emit_band_glue.py"), ZZL, str(H), raw])
    src = open(raw).read()
    os.remove(raw)
    src = src.replace("/-  BandGlue_h%d.lean --" % H, "/-  Arb4_BandGlue_h%d.lean --" % H)
    src = src.replace("    GENERATED by telperion/examples/zeta_reflection/emit_band_glue.py; DO NOT EDIT BY HAND.",
                      "    GENERATED by telperion/examples/zeta_reflection/emit_band_glue.py; DO NOT EDIT BY HAND.\n"
                      "    (Lane Arb4: `emit_band_glue.py ../zeta_zero_localization/lean %d`, unmodified except the\n"
                      "    module name and the namespace, prefixed `Arb4.` so a later `BandGlue_h%d` cannot clash.)" % (H, H))
    src = src.replace("namespace BandGlue_h%d" % H, "namespace Arb4.BandGlue_h%d" % H)
    src = src.replace("end BandGlue_h%d" % H, "end Arb4.BandGlue_h%d" % H)
    open(os.path.join(LEAN, "Arb4_BandGlue_h%d.lean" % H), "w").write(src)
    mods = re.findall(r"exact (RHInBoxT_[0-9a-z_]+)\.statement_match", src)
    sys.path.insert(0, HERE)
    import Arb4_emit_seg as ES
    from fractions import Fraction as Fr
    bands = ES.parse_bandglue(os.path.join(LEAN, "Arb4_BandGlue_h%d.lean" % H))
    nb = len(bands)
    assert len(mods) == nb, (len(mods), nb)
    heights = set([b["T0"] for b in bands] + [b["T1"] for b in bands])
    # the edge at H - 1000 is the previous segment's when that segment emitted it (Arb4_emit_seg reuse rule)
    n_edges = len(heights) - (1 if (Fr(H - 1000) in heights and ES.prev_edge_emitted(LEAN, H)) else 0)
    n_ef = -(-n_edges // 5)             # --edges-per-file 5
    n_sf = -(-2 * nb // 10)             # --slabs-per-file 10 (a lower and an upper slab per band)
    n_lf = -(-nb // 5)                  # --bands-per-file 5
    roots = ", ".join('"%s"' % m for m in ["AllZeros_h%d" % H] + mods)
    lib = lambda name, rs: '[[lean_lib]]\nname = "%s"\nroots = [%s]\n' % (name, ", ".join('"%s"' % r for r in rs))
    block = """
# ---------------------------------------------------------------------------------------------
# Lane Arb4: the COMPACT hypothesis-free [%d, %d] segment (Arb4_prepare_seg.py %d + Arb4_emit_seg.py
# --seg %d): zzl band plan sources (unchanged), band table, certificates, capstone
# `Arb4_h%d.all_nontrivial_zeros_up_to_height_%d` (no hypotheses), guard.  conjecture1_proved = False.
# ---------------------------------------------------------------------------------------------
[[lean_lib]]
name = "Arb4_ZZLSegment_h%d"
srcDir = "../../zeta_zero_localization/lean"
roots = [%s]

""" % (H - 1000, H, H, H, H, H, H, roots)
    block += lib("Arb4_BandGlue_h%d" % H, ["Arb4_BandGlue_h%d" % H]) + "\n"
    block += lib("Arb4_H%dEdges" % H, ["Arb4_H%dEdges_%d" % (H, k) for k in range(n_ef)]) + "\n"
    block += lib("Arb4_H%dSlabs" % H, ["Arb4_H%dSlabs_%d" % (H, k) for k in range(n_sf)]) + "\n"
    block += lib("Arb4_H%dLines" % H, ["Arb4_H%dLines_%d" % (H, k) for k in range(n_lf)]) + "\n"
    block += lib("Arb4_h%d" % H, ["Arb4_h%d" % H]) + "\n"
    block += lib("Arb4_AxiomGuard_h%d" % H, ["Arb4_AxiomGuard_h%d" % H])
    lf = os.path.join(LEAN, "lakefile.toml")
    s = open(lf).read()
    assert 'name = "Arb4_h%d"' % H not in s, "segment already registered"
    open(lf, "w").write(s.rstrip("\n") + "\n" + block)
    print("prepared segment %d: Arb4_BandGlue_h%d.lean + lakefile entries (%d bands, %d edge / %d slab / %d line "
          "files)" % (H, H, nb, n_ef, n_sf, n_lf))


if __name__ == "__main__":
    main()
