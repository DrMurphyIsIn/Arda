"""Generate an ORDER-(2K+1) Euler-Maclaurin instance (lane emhigh) for one height.

usage: gen_emhigh.py TAG t K N [P CHUNK CHUNKS_PER_FILE OUTDIR] [--lnbig L] [--sqbig S]
  t a positive integer height (the evaluator supports t = tn / 2^tq; instances use tq = 0),
  K in 1..6 (the finite part carries B_2 .. B_2K), N the EM cut (Dirichlet sum over 1..N-1).
writes (OUTDIR default = ../lean):
  EMZetaHigh_<TAG>_Cfg.lean   unrolled kernels, cfg, chunk-boundary states (the SAME Nat-only
                              evaluator as Probes/ArbEconomics_Eval, reused unchanged)
  EMZetaHigh_<TAG>_P<j>.lean  kernel chunk theorems (decide +kernel)
  EMZetaHigh_<TAG>.lean       assembly: Valid, invariant chain (ArbEcon.chunk_sound), the
                              order-(2K+1) remainder (EMZetaHigh.em_line_remainder_le), the exact
                              correction factor (EMZetaHigh.emCorrRe/Im by norm_num), and the final
                              theorems zeta_re / zeta_im
and prints a JSON summary.  conjecture1_proved = False.
"""
import sys
import os
import json
import time
import math
from fractions import Fraction
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import arbecon_model as M

DIGITS = 8
BERN = {2: Fraction(1, 6), 3: Fraction(0), 4: Fraction(-1, 30), 5: Fraction(0), 6: Fraction(1, 42),
        7: Fraction(0), 8: Fraction(-1, 30), 9: Fraction(0), 10: Fraction(5, 66), 11: Fraction(0),
        12: Fraction(-691, 2730), 13: Fraction(0)}
BERN_LEMMA = {4: "bernoulli_four'", 6: "bernoulli_six'", 8: "bernoulli_eight'", 10: "bernoulli_ten'",
              12: "bernoulli_twelve'"}


def frac_lean(q):
    q = Fraction(q)
    if q.denominator == 1:
        return "(%d : ℝ)" % q.numerator
    return "((%d : ℝ) / %d)" % (q.numerator, q.denominator)


def poch_ri(sig, t, k):
    x, y = Fraction(1), Fraction(0)
    for j in range(k):
        x, y = x * (sig + j) - y * t, x * t + y * (sig + j)
    return x, y


def corr(K, t, N):
    """exact (Re, Im) of EMZetaHigh.emCorr K (1/2 + i t) N"""
    sig = Fraction(1, 2)
    t = Fraction(t)
    d = (sig - 1) ** 2 + t * t
    re = Fraction(N) * (sig - 1) / d + Fraction(1, 2)
    im = -Fraction(N) * t / d
    for i in range(2 * K - 1):
        c = BERN[i + 2] / math.factorial(i + 2) / Fraction(N) ** (i + 1)
        x, y = poch_ri(sig, t, i + 1)
        re += c * x
        im += c * y
    return re, im


def poch_norm_sq(t, k):
    p = Fraction(1)
    for j in range(k):
        p *= (Fraction(1, 2) + j) ** 2 + Fraction(t) ** 2
    return p


def remainder(K, t, N, qdigits=6):
    """(Q, r, E): Q^2 >= prod_{j<2K} ((1/2+j)^2 + t^2), r = isqrt N, E the proved bound."""
    prod = poch_norm_sq(t, 2 * K)
    D = 10 ** qdigits
    Q = Fraction(math.isqrt(int(prod * D * D)) + 1, D)
    assert Q * Q >= prod
    r = math.isqrt(N)
    E = abs(BERN[2 * K]) / math.factorial(2 * K) * Q / (Fraction(N) ** (2 * K - 1) * r) / (Fraction(2 * K) - Fraction(1, 2))
    return Q, r, E


def minimal_N(K, t, eps):
    lo, hi = 2, 10 ** 8
    while lo < hi:
        m = (lo + hi) // 2
        if remainder(K, t, m, 3)[2] <= eps:
            hi = m
        else:
            lo = m + 1
    return lo


def main():
    argv = sys.argv[1:]
    opts, args, i = {}, [], 0
    while i < len(argv):
        if argv[i].startswith("--"):
            opts[argv[i][2:]] = int(argv[i + 1])
            i += 2
        else:
            args.append(argv[i])
            i += 1
    tag, t, K, N = args[0], int(args[1]), int(args[2]), int(args[3])
    P = int(args[4]) if len(args) > 4 else 64
    chunk = int(args[5]) if len(args) > 5 else 500
    cpf = int(args[6]) if len(args) > 6 else 40
    outdir = args[7] if len(args) > 7 else os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "lean")
    assert 1 <= K <= 6
    tn, tq = t, 0
    c = M.make_cfg(P, tn, tq, lnbig=opts.get("lnbig"), sqbig=opts.get("sqbig"))
    Kh = len(c.dcos)
    t0 = time.time()
    s = M.init_state(c)
    states, lens, idx = [s], [], [1]
    total, done = N - 2, 0
    while done < total:
        L = min(chunk, total - done)
        s = M.run(c, s, L)
        states.append(s)
        lens.append(L)
        done += L
        idx.append(idx[-1] + L)
    sN = M.step(c, states[-1])
    pyt = time.time() - t0
    assert states[-1].n == N - 1 and sN.n == N
    base = "EMZetaHigh_%s" % tag
    ns = "ArbEcon.IK_%s" % tag
    cfgmod = base + "_Cfg"
    nch = len(lens)
    # ------------------------------------------------------------ config / state module
    L = []
    L.append("/-  %s.lean -- order-(2K+1) EM instance data (GENERATED by arbecon/gen_emhigh.py; do not edit)." % cfgmod)
    L.append("")
    L.append("    t = %d, K = %d (finite part through B_%d), EM cut N = %d (Dirichlet sum over n = 1..%d)," % (t, K, 2 * K, N, N - 1))
    L.append("    P = %d bits.  Unrolled kernels, the evaluator configuration (Probes/ArbEconomics_Eval, reused" % P)
    L.append("    unchanged) and the %d chunk-boundary states (plus the state after term N)." % len(states))
    L.append("    conjecture1_proved = False.")
    L.append("-/")
    L.append("import Probes.ArbEconomics_Eval")
    L.append("")
    L.append("namespace %s" % ns)
    L.append("")
    L.append("noncomputable section")
    L.append("")
    L.append(M.lean_horner(c.one, c.dcos, "hc"))
    L.append("")
    L.append(M.lean_horner(c.one, c.dsin, "hs"))
    L.append("")
    L.append(M.lean_lnf(c, "lnf"))
    L.append("")
    L.append("def cfg : ArbEcon.Cfg := %s" % M.cfg_lean(c, "hc", "hs", "lnf"))
    L.append("")
    for i, st in enumerate(states):
        L.append("def s%d : ArbEcon.St := %s" % (i, M.st_lean(st)))
    L.append("def sN : ArbEcon.St := %s" % M.st_lean(sN))
    L.append("")
    L.append("end")
    L.append("")
    L.append("end %s" % ns)
    L.append("")
    with open(os.path.join(outdir, cfgmod + ".lean"), "w") as f:
        f.write("\n".join(L))
    # ------------------------------------------------------------ chunk parts
    parts = []
    for j, start in enumerate(range(0, nch, cpf)):
        stop = min(start + cpf, nch)
        pm = "%s_P%d" % (base, j)
        L = []
        L.append("/-  %s.lean -- kernel chunks %d..%d (GENERATED by arbecon/gen_emhigh.py; do not edit)." % (pm, start, stop - 1))
        L.append("    Each `chunk_i` is a kernel `decide +kernel` check that `ArbEcon.run` maps s_i to s_(i+1).")
        L.append("    conjecture1_proved = False.")
        L.append("-/")
        L.append("import %s" % cfgmod)
        L.append("")
        L.append("namespace %s" % ns)
        L.append("")
        for i in range(start, stop):
            L.append("theorem chunk_%d : ArbEcon.St.beq (ArbEcon.run cfg %d s%d) s%d = true := by decide +kernel"
                     % (i, lens[i], i, i + 1))
        if stop == nch:
            L.append("theorem chunk_N : ArbEcon.St.beq (ArbEcon.run cfg 1 s%d) sN = true := by decide +kernel" % nch)
        L.append("")
        L.append("end %s" % ns)
        L.append("")
        with open(os.path.join(outdir, pm + ".lean"), "w") as f:
            f.write("\n".join(L))
        parts.append(pm)
    # ------------------------------------------------------------ numerics of the final bound
    s1 = states[-1]
    one = c.one
    Bre, Bim = corr(K, t, N)
    aRe, aIm = abs(Bre), abs(Bim)
    Q, r, E = remainder(K, t, N)
    a1 = s1.reP - s1.reN
    b1 = s1.imP - s1.imN
    za = (sN.reP - sN.reN) - a1
    zb = (sN.imP - sN.imN) - b1
    zra = sN.reR + s1.reR
    zrb = sN.imR + s1.imR
    Cre = a1 + za * Bre - zb * Bim
    Rre = s1.reR + zra * aRe + zrb * aIm + E * one
    Cim = b1 + za * Bim + zb * Bre
    Rim = s1.imR + zra * aIm + zrb * aRe + E * one
    D = 10 ** DIGITS
    lo_re = Fraction(math.floor((Cre - Rre) / one * D), D)
    hi_re = Fraction(math.ceil((Cre + Rre) / one * D), D)
    lo_im = Fraction(math.floor((Cim - Rim) / one * D), D)
    hi_im = Fraction(math.ceil((Cim + Rim) / one * D), D)
    B2K = BERN[2 * K]
    bern_lemmas = ", ".join("ZetaReflection.EMHigh.%s" % BERN_LEMMA[2 * j] for j in range(2, K + 1))
    bern_simp = "bernoulli_two" + (", " + bern_lemmas if bern_lemmas else "")
    Elean = "(%s / %d * %s / ((%d : ℝ) ^ %d * %d) / %s)" % (
        frac_lean(abs(B2K)), math.factorial(2 * K), frac_lean(Q), N, 2 * K - 1, r, frac_lean(Fraction(4 * K - 1, 2)))
    # ------------------------------------------------------------ assembly module
    L = []
    L.append("/-  %s.lean -- KERNEL-CHECKED order-%d Euler-Maclaurin enclosure of zeta(1/2 + %d i)" % (base, 2 * K + 1, t))
    L.append("    (GENERATED by arbecon/gen_emhigh.py; do not edit).")
    L.append("")
    L.append("    `zeta_re`, `zeta_im` bound Re / Im of riemannZeta (1/2 + %d i) with NO hypotheses:" % t)
    L.append("      * the Dirichlet sum over n = 1..%d is kernel-evaluated in %d `decide +kernel` chunks" % (N - 1, nch))
    L.append("        (the unchanged ArbEconomics evaluator, composed by `ArbEcon.chunk_sound`);")
    L.append("      * the order-%d finite part (K = %d: Bernoulli corrections B_2 .. B_%d) and its PROVED" % (2 * K + 1, K, 2 * K))
    L.append("        remainder at N = %d are `EMZetaHigh.em_line_remainder_le` (general-K theorem):" % N)
    L.append("        E = |B_%d| / %d! * Q / (N^%d r) / (%d/2), Q = %s, r = %d;" % (2 * K, 2 * K, 2 * K - 1, 4 * K - 1, str(Q), r))
    L.append("      * the correction factor Re/Im (exact rationals) by `norm_num` from `EMZetaHigh.emCorrRe/Im`;")
    L.append("      * `ArbEcon.OrderK.zetaK_re_bounds` / `zetaK_im_bounds` (EMZetaHighEval) assemble the result.")
    L.append("    Certified: Re in [%s, %s], Im in [%s, %s] (E = %.3g)." % (
        float(lo_re), float(hi_re), float(lo_im), float(hi_im), float(E)))
    L.append("    conjecture1_proved = False.  One height, finite interval arithmetic; nothing about RH.")
    L.append("-/")
    L.append("import EMZetaHighEval")
    for pm in parts:
        L.append("import %s" % pm)
    L.append("")
    L.append("namespace %s" % ns)
    L.append("")
    L.append("theorem valid : ArbEcon.Valid cfg (%d : ℝ) %d where" % (t, Kh))
    L.append("  one_eq := by decide")
    L.append("  two1_eq := by decide")
    L.append("  oneSq_eq := by decide")
    L.append("  t_eq := by show (%d : ℝ) = ((%d : ℕ) : ℝ) / 2 ^ (%d : ℕ); norm_num" % (t, tn, tq))
    L.append("  pi_ball := by")
    L.append("    show |Real.pi / 2 * 2 ^ (%d : ℕ) - ((%d : ℕ) : ℝ)| ≤ ((%d : ℕ) : ℝ)" % (P, c.hp, c.rp))
    L.append("    have h1 := Real.pi_gt_d20")
    L.append("    have h2 := Real.pi_lt_d20")
    L.append("    rw [abs_le]; constructor <;> norm_num <;> linarith")
    L.append("  umax_le := by decide")
    L.append("  dcos_eq := by decide")
    L.append("  dsin_eq := by decide")
    L.append("  tau_ok := by")
    L.append("    show (2 : ℝ) ^ (%d : ℕ) * ArbEcon.taylorBnd %d ≤ ((%d : ℕ) : ℝ)" % (P, Kh, c.tau))
    L.append("    unfold ArbEcon.taylorBnd; norm_num [Nat.factorial]")
    L.append("  hc_eq := fun _ => rfl")
    L.append("  hs_eq := fun _ => rfl")
    L.append("  lnf_eq := fun _ => rfl")
    L.append("")
    L.append("theorem inv_0 : ArbEcon.Inv cfg (%d : ℝ) 1 s0 := ArbEcon.inv_init cfg _ valid.one_eq" % t)
    for i in range(nch):
        L.append("theorem inv_%d : ArbEcon.Inv cfg (%d : ℝ) %d s%d :=\n  ArbEcon.chunk_sound cfg _ %d valid %d %d s%d s%d inv_%d chunk_%d"
                 % (i + 1, t, idx[i + 1], i + 1, Kh, lens[i], idx[i], i, i + 1, i, i))
    L.append("theorem inv_N : ArbEcon.Inv cfg (%d : ℝ) %d sN :=\n  ArbEcon.chunk_sound cfg _ %d valid 1 %d s%d sN inv_%d chunk_N"
             % (t, N, Kh, N - 1, nch, nch))
    L.append("")
    L.append("/-- The order-%d EM remainder at N = %d, from the general-K theorem. -/" % (2 * K + 1, N))
    L.append("theorem remainder :")
    L.append("    ‖riemannZeta (ArbEcon.sOf %d) - ZetaReflection.EMHigh.emFinite %d (ArbEcon.sOf %d) %d‖" % (t, K, t, N))
    L.append("      ≤ %s := by" % Elean)
    L.append("  have h := ZetaReflection.EMHigh.em_line_remainder_le %d (by norm_num) (%d : ℝ) (N := %d) (by norm_num)" % (K, t, N))
    L.append("    %s (by norm_num) (by norm_num [ZetaReflection.EMHigh.pochNormSq]) %d (by norm_num) (by norm_num)" % (frac_lean(Q), r))
    L.append("  refine le_trans h (le_of_eq ?_)")
    L.append("  norm_num [%s, Nat.factorial]" % bern_simp)
    L.append("")
    L.append("/-- Re of the order-%d correction factor at t = %d, N = %d (exact rational). -/" % (2 * K + 1, t, N))
    L.append("theorem corr_re : ZetaReflection.EMHigh.emCorrRe %d (1 / 2) (%d : ℝ) %d = %s := by" % (K, t, N, frac_lean(Bre)))
    L.append("  norm_num [ZetaReflection.EMHigh.emCorrRe, ZetaReflection.EMHigh.pochRI, Finset.sum_range_succ,")
    L.append("    %s, ZetaReflection.EMHigh.bernoulli_odd_vanish, Nat.factorial]" % bern_simp)
    L.append("")
    L.append("/-- Im of the order-%d correction factor at t = %d, N = %d (exact rational). -/" % (2 * K + 1, t, N))
    L.append("theorem corr_im : ZetaReflection.EMHigh.emCorrIm %d (1 / 2) (%d : ℝ) %d = %s := by" % (K, t, N, frac_lean(Bim)))
    L.append("  norm_num [ZetaReflection.EMHigh.emCorrIm, ZetaReflection.EMHigh.pochRI, Finset.sum_range_succ,")
    L.append("    %s, ZetaReflection.EMHigh.bernoulli_odd_vanish, Nat.factorial]" % bern_simp)
    L.append("")
    common = ("cfg %d %d %d (by norm_num) s%d sN inv_%d inv_N _ remainder %s %s corr_re corr_im %s %s"
              % (K, t, N, nch, nch, frac_lean(Bre), frac_lean(Bim), frac_lean(aRe), frac_lean(aIm)))
    L.append("/-- **Re zeta(1/2 + %d i)**, kernel-checked, no hypotheses (order-%d Euler-Maclaurin). -/" % (t, 2 * K + 1))
    L.append("theorem zeta_re : %s ≤ (riemannZeta ((1 / 2 : ℂ) + ((%d : ℝ) : ℂ) * Complex.I)).re ∧" % (frac_lean(lo_re), t))
    L.append("    (riemannZeta ((1 / 2 : ℂ) + ((%d : ℝ) : ℂ) * Complex.I)).re ≤ %s :=" % (t, frac_lean(hi_re)))
    L.append("  ArbEcon.OrderK.zetaK_re_bounds %s %s %s" % (common, frac_lean(lo_re), frac_lean(hi_re)))
    L.append("    (by rw [abs_le]; constructor <;> norm_num) (by rw [abs_le]; constructor <;> norm_num)")
    L.append("    (by norm_num [s%d, sN, cfg]) (by norm_num [s%d, sN, cfg])" % (nch, nch))
    L.append("")
    L.append("/-- **Im zeta(1/2 + %d i)**, kernel-checked, no hypotheses (order-%d Euler-Maclaurin). -/" % (t, 2 * K + 1))
    L.append("theorem zeta_im : %s ≤ (riemannZeta ((1 / 2 : ℂ) + ((%d : ℝ) : ℂ) * Complex.I)).im ∧" % (frac_lean(lo_im), t))
    L.append("    (riemannZeta ((1 / 2 : ℂ) + ((%d : ℝ) : ℂ) * Complex.I)).im ≤ %s :=" % (t, frac_lean(hi_im)))
    L.append("  ArbEcon.OrderK.zetaK_im_bounds %s %s %s" % (common, frac_lean(lo_im), frac_lean(hi_im)))
    L.append("    (by rw [abs_le]; constructor <;> norm_num) (by rw [abs_le]; constructor <;> norm_num)")
    L.append("    (by norm_num [s%d, sN, cfg]) (by norm_num [s%d, sN, cfg])" % (nch, nch))
    L.append("")
    L.append("end %s" % ns)
    L.append("")
    with open(os.path.join(outdir, base + ".lean"), "w") as f:
        f.write("\n".join(L))
    try:
        import mpmath
        mpmath.mp.dps = 30
        z = mpmath.zeta(mpmath.mpc(0.5, t))
        inside = bool(lo_re <= Fraction(str(z.real)) <= hi_re and lo_im <= Fraction(str(z.imag)) <= hi_im)
        zre, zim = float(z.real), float(z.imag)
    except ImportError:
        inside, zre, zim = None, None, None
    summary = dict(mpmath_re=zre, mpmath_im=zim, mpmath_inside=inside, tag=tag, t=t, K=K, order=2 * K + 1, N=N, P=P, chunk=chunk, nchunks=nch, terms=N - 1,
                   python_seconds=round(pyt, 2), cfg_module=cfgmod, parts=parts, assembly=base,
                   lo_re=float(lo_re), hi_re=float(hi_re), lo_im=float(lo_im), hi_im=float(hi_im),
                   E=float(E), Q=str(Q), r=r, Bre=float(Bre), Bim=float(Bim),
                   rad_re=float(Rre / one), rad_im=float(Rim / one),
                   eval_rad_re=float((s1.reR + zra * aRe + zrb * aIm) / one),
                   lnbig=c.lnbig, sqbig=c.sqbig)
    print(json.dumps(summary))


if __name__ == "__main__":
    main()
